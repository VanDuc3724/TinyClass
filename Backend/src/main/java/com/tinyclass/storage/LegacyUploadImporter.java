package com.tinyclass.storage;

import org.slf4j.*;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.*;
import org.springframework.stereotype.Component;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;
import java.io.*;
import java.nio.file.*;
import java.util.Objects;

/**
 * Until V19, LOCAL bytes were files under TINYCLASS_UPLOAD_ROOT. At startup, copies each READY file still missing its
 * chunks from that directory into the database, keeping it only when size and SHA-256 match the metadata. The directory
 * is only read; once nothing is left to import it can be removed.
 */
@Component
public class LegacyUploadImporter implements ApplicationRunner {
    private static final Logger log = LoggerFactory.getLogger(LegacyUploadImporter.class);
    private final StoredFileRepository files;
    private final DatabaseStorageAdapter storage;
    private final TransactionTemplate tx;
    private final String root;
    public LegacyUploadImporter(StoredFileRepository files, DatabaseStorageAdapter storage, PlatformTransactionManager transactions,
            @Value("${tinyclass.storage.legacy-root:}") String root) {
        this.files = files; this.storage = storage; this.tx = new TransactionTemplate(transactions); this.root = root;
    }
    @Override public void run(ApplicationArguments args) { if (!root.isBlank()) importFrom(Path.of(root)); }
    public int importFrom(Path directory) {
        Path base = directory.toAbsolutePath().normalize();
        if (!Files.isDirectory(base, LinkOption.NOFOLLOW_LINKS)) return 0;
        int imported = 0;
        for (var file : files.readyWithoutContent()) {
            // Keys were generated by the server as teacher/file.ext; anything else is not read from disk.
            Path source = base.resolve(file.getStorageKey()).normalize();
            if (!file.getStorageKey().matches("[a-f0-9-]{36}/[a-f0-9-]{36}\\.[a-z0-9]{2,5}") || !source.startsWith(base)
                    || !Files.isRegularFile(source, LinkOption.NOFOLLOW_LINKS)) {
                log.warn("Legacy bytes for file {} are not in {}; it stays unavailable", file.getId(), base);
                continue;
            }
            try (var input = Files.newInputStream(source, LinkOption.NOFOLLOW_LINKS)) {
                tx.executeWithoutResult(status -> {
                    StorageAdapter.Written written;
                    try { written = storage.write(file, input, file.getSizeBytes()); } catch (IOException failure) { throw new UncheckedIOException(failure); }
                    if (written.size() != file.getSizeBytes() || !Objects.equals(written.checksum(), file.getChecksum()))
                        throw new IllegalStateException("bytes differ from the recorded size or checksum");
                });
                imported++;
            } catch (IOException | RuntimeException failure) {
                log.warn("Could not import legacy bytes for file {}: {}", file.getId(), failure.getMessage());
            }
        }
        if (imported > 0) log.info("Imported {} legacy file(s) from {} into PostgreSQL", imported, base);
        return imported;
    }
}
