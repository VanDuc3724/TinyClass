package com.tinyclass.storage;

import com.tinyclass.common.api.ApiException;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.*;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Component;
import java.io.*;
import java.nio.file.*;
import java.security.*;
import java.util.HexFormat;

@Component
public class LocalStorageAdapter implements StorageAdapter {
    private final Path root;
    public LocalStorageAdapter(@Value("${tinyclass.storage.local-root}") String configuredRoot) throws IOException {
        root = Path.of(configuredRoot).toAbsolutePath().normalize();
        // Never serve the upload directory as static web content or place it in a build directory.
        if (root.getParent() == null || root.toString().matches("(?i).*[\\\\/](static|public|dist|target|node_modules)([\\\\/].*)?"))
            throw new IllegalStateException("Choose a private persistent upload directory outside public/build directories.");
        Files.createDirectories(root);
        if (!root.toRealPath().equals(root)) throw new IllegalStateException("Upload root cannot contain symbolic links.");
    }
    @Override public String provider() { return "LOCAL"; }
    private Path resolve(String key) throws IOException {
        // The key is generated by the server, never by a filename from a browser.
        if (key == null || !key.matches("[a-f0-9-]{36}/[a-f0-9-]{36}\\.[a-z0-9]{2,5}")) throw new IOException("Invalid storage key");
        Path candidate = root.resolve(key).normalize();
        if (!candidate.startsWith(root) || Files.isSymbolicLink(candidate) || Files.isSymbolicLink(candidate.getParent()))
            throw new IOException("Invalid storage path");
        return candidate;
    }
    @Override public Written write(String key, InputStream source, long limit) throws IOException {
        Path target = resolve(key); Files.createDirectories(target.getParent());
        if (!target.getParent().toRealPath().startsWith(root)) throw new IOException("Invalid storage path");
        Path temporary = Files.createTempFile(target.getParent(), ".upload-", ".part");
        try {
            MessageDigest digest;
            try { digest = MessageDigest.getInstance("SHA-256"); } catch (NoSuchAlgorithmException e) { throw new IllegalStateException(e); }
            long size = 0; byte[] buffer = new byte[65536]; int read;
            try (var output = Files.newOutputStream(temporary)) {
                while ((read = source.read(buffer)) != -1) {
                    size += read;
                    if (size > limit) throw new ApiException(HttpStatus.PAYLOAD_TOO_LARGE, "FILE_TOO_LARGE", "Tệp vượt quá giới hạn cho phép.");
                    digest.update(buffer, 0, read); output.write(buffer, 0, read);
                }
            }
            Files.move(temporary, target, StandardCopyOption.ATOMIC_MOVE);
            return new Written(size, HexFormat.of().formatHex(digest.digest()));
        } finally { Files.deleteIfExists(temporary); }
    }
    @Override public Resource read(String key, long size) throws IOException {
        Path target = resolve(key);
        if (!Files.isRegularFile(target, LinkOption.NOFOLLOW_LINKS) || Files.size(target) != size) throw new IOException("File unavailable");
        return new FileSystemResource(target);
    }
    @Override public void delete(String key) throws IOException { Files.deleteIfExists(resolve(key)); }
}
